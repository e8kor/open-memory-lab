#!/usr/bin/env python3
"""Build the landing site into site/dist/ (site/README.md).

    python site/build.py                 # write site/dist/
    python site/build.py --check         # exit 1 if site/dist/ differs from what this would write
    python site/build.py --legal-links   # the footers link Privacy and Terms

Inputs: the page sources in site/src/, the design system's outputs in site/design/ (written by
scripts/gen_design_tokens.py, ADR-0069) and the workspace version in Cargo.toml, which the
footer and the install command name. Output: one self-contained HTML file per page, inline CSS,
inline marks, no external assets, plus the two legal drafts copied as they are. The release
packs site/dist/ as oml-site-<version>.tar.gz.

Standard library only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path

SITE = Path(__file__).resolve().parent
ROOT = SITE.parent
SRC = SITE / "src"
DESIGN = SITE / "design"
DIST = SITE / "dist"
HEAD = "Generated by site/build.py from site/src/ and design/ (ADR-0069). Do not edit."
# The pages: published path, header label (None: not in the nav).
PAGES = (("index", None), ("teams", "Teams"), ("personal", "Personal"))
# Copied as they are: drafts until the operator publishes them.
STATIC = ("privacy.html", "terms.html")
DOCS_URL = "https://e8kor.github.io/open-memory-lab/"
GITHUB_URL = "https://github.com/e8kor/open-memory-lab"
# The footers link /privacy and /terms only with --legal-links: both are drafts until the
# operator publishes them (site/README.md).
LEGAL_LINKS = False
# Where "Ask about access" goes, and the address the footer shows so it works without a mail
# client. The operator swaps either for a form or another address here.
CONTACT_EMAIL = "contact@doublegate.io"
CONTACT_URL = f"mailto:{CONTACT_EMAIL}?subject=OML%20access"
DISCUSSIONS_URL = f"{GITHUB_URL}/discussions"


def workspace_version() -> str:
    """The version the release ships, from the workspace manifest, so the footer and the
    install command name the release this tree builds."""
    return tomllib.loads((ROOT / "Cargo.toml").read_text())["workspace"]["package"]["version"]


def header(page: str, brand: dict) -> str:
    current = ' aria-current="page"'
    nav = "".join(f'<a href="/{name}"{current if name == page else ""}>{label}</a>'
                  for name, label in PAGES if label)
    nav += f'<a href="{DOCS_URL}">Docs</a><a href="{GITHUB_URL}">GitHub</a>'
    return ('<header class="top">\n'
            f'  <a class="brand" href="/" aria-label="Open Memory Lab home">{brand["wordmark"]}{brand["mark"]}</a>\n'
            f'  <nav aria-label="Main">{nav}</nav>\n'
            '  <span class="end"><a class="btn sm" href="/web">Sign in</a></span>\n'
            '</header>')


def footer(version: str, legal: bool) -> str:
    links = (f'<a href="{DOCS_URL}">Docs</a><a href="{GITHUB_URL}">GitHub</a>'
             f'<a href="{GITHUB_URL}/blob/main/LICENSE">License</a>')
    if legal:
        links += '<a href="/privacy">Privacy</a><a href="/terms">Terms</a>'
    return ('<footer>\n'
            f'  <span>Open Memory Lab · Apache-2.0 · memory.doublegate.io v{version}</span>\n'
            f'  <nav aria-label="Footer">{links}<a href="{CONTACT_URL}">{CONTACT_EMAIL}</a></nav>\n'
            '</footer>')


def strip_head(css: str) -> str:
    """A generated stylesheet without its leading generated-by comment."""
    return re.sub(r"^/\*.*?\*/\n", "", css, count=1, flags=re.S).strip()


def pages(src: Path = SRC, design: Path = DESIGN, legal: bool = LEGAL_LINKS,
          version: str | None = None) -> dict[str, bytes]:
    """Every file of site/dist/, by name."""
    brand = json.loads((design / "brand.json").read_text())
    tokens = (design / "tokens.css").read_text().strip()
    fonts = strip_head((design / "fonts.css").read_text())
    version = version or workspace_version()
    style = (src / "landing.src.css").read_text().strip()
    style = style.replace("{{TOKENS}}", tokens).replace("{{FONTS}}", fonts)
    out: dict[str, bytes] = {}
    for page, _ in PAGES:
        subs = {
            "{{STYLE}}": style,
            "{{HEADER}}": header(page, brand),
            "{{FOOTER}}": footer(version, legal),
            "{{VERSION}}": version,
            "{{CONTACT_URL}}": CONTACT_URL,
            "{{CONTACT_EMAIL}}": CONTACT_EMAIL,
            "{{DISCUSSIONS_URL}}": DISCUSSIONS_URL,
            "{{DOCS_URL}}": DOCS_URL,
            "{{GROUND_DARK}}": brand["ground"]["dark"],
            "{{GROUND_LIGHT}}": brand["ground"]["light"],
            "{{FAVICON}}": brand["favicon"],
            "{{GATE_WIDE}}": brand["gate_wide"],
            "{{GATE_TALL}}": brand["gate_tall"],
        }
        html = (src / f"{page}.src.html").read_text()
        for k, v in subs.items():
            html = html.replace(k, v)

        def glyph(m: re.Match) -> str:
            if m.group(1) not in brand["glyphs"]:
                raise ValueError(f"site/src/{page}.src.html names glyph {m.group(1)!r}, which design/glyphs/ lacks")
            return brand["glyphs"][m.group(1)]
        html = re.sub(r"\{\{GLYPH:([\w-]+)\}\}", glyph, html)
        left = re.findall(r"\{\{[A-Za-z_:-]+\}\}", html)
        if left:
            raise ValueError(f"unfilled placeholders in site/src/{page}.src.html: {left}")
        out[f"{page}.html"] = (f"<!-- {HEAD} Source: site/src/{page}.src.html. -->\n" + html).encode()
    for name in STATIC:
        out[name] = (src / name).read_bytes()
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if site/dist/ differs from what this would write")
    ap.add_argument("--legal-links", action="store_true", default=LEGAL_LINKS,
                    help="link /privacy and /terms from the footers (off while they are drafts)")
    ap.add_argument("--out", type=Path, default=DIST, help="the directory to write (default site/dist/)")
    args = ap.parse_args(argv)
    try:
        files = pages(legal=args.legal_links)
    except ValueError as e:
        print(e, file=sys.stderr)
        return 1
    want = set(files)
    have = {p.name for p in args.out.iterdir() if p.is_file()} if args.out.is_dir() else set()
    if args.check:
        stale = sorted(n for n in want if not (args.out / n).exists() or (args.out / n).read_bytes() != files[n])
        extra = sorted(have - want)
        if stale or extra:
            print("site/dist is out of date (run python site/build.py):",
                  *stale, *(f"{n} (not built from site/src)" for n in extra), sep="\n  ", file=sys.stderr)
            return 1
        return 0
    args.out.mkdir(parents=True, exist_ok=True)
    for name in sorted(have - want):
        (args.out / name).unlink()
        print(f"removed {args.out.name}/{name}")
    for name, data in files.items():
        path = args.out / name
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
            print(f"wrote {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
