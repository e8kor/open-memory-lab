"""Shared helpers for the scripts that write docs/ pages from the code and the contracts.

A generated page is a function of its source: each generator renders the page text, then either
writes it or, under --check, compares it with the file on disk and exits 1 on any difference.
`VERIFIED` is the date a person last confirmed the generated pages against a release; raise it in
the same change that regenerates them for a new one.
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
VERIFIED = "2026-11-06"
BANNER = "Generated by `{script}`; edit the source, not this page."

# "(ADR-0039 d15)", "(proposed ADR-0037 d2, d10)", "(admin key role; ADR-0049 d4)", "ADR-0015", "#117".
_PAREN_ONLY = re.compile(r"\s*\((?:[^()]*?;\s*)?(?:proposed\s+)?(?:ADR-\d+(?:\s*d[\d, –-]+\d?)?(?:\s*,\s*)?)+\)")
_ADR = re.compile(r"[,;]?\s*(?:proposed\s+)?ADR-\d+(?:\s*d\d+(?:\s*[-–,]\s*d?\d+)*)?")
_ISSUE = re.compile(r"\s*\(?#\d{2,4}\)?")
_DNUM = re.compile(r"\b[Dd]\d{1,2}(?:[-–,]\s*d?\d{1,2})*\b")


def strip_handles(text: str) -> str:
    """Remove ADR and issue handles from a sentence; they belong to contributors, not readers."""
    before = None
    while before != text:
        before = text
        text = _PAREN_ONLY.sub("", text)
    text = re.sub(r"\(([^()]*?);\s*(?:proposed\s+)?ADR-\d+[^()]*\)", r"(\1)", text)
    text = _ADR.sub("", text)
    text = _ISSUE.sub("", text)
    text = re.sub(r"\s*\([Dd]\d{1,2}(?:\s*[-–,]\s*[Dd]?\d{1,2})*\)", "", text)
    text = re.sub(r"\(\s*[;,]\s*", "(", text)
    text = re.sub(r"\(\s*\)", "", text)
    text = re.sub(r"\s+([,.;:)])", r"\1", text)
    text = re.sub(r"\(\s+", "(", text)
    return re.sub(r"[ \t]{2,}", " ", text).strip()


NOT_RELEASED = "Not released yet (next release)."

# Text the build carries that the last release (v0.6.0) does not. Each pair is the generated text
# and what the page shows instead. Remove a pair in the change that releases the feature; a pair
# whose text is gone from the output stops the generator, so a stale entry cannot stay.
UNRELEASED = {
    "cli": [
        ("Adapter: adr, headings, lines, rust, or delta. Defaults to adr for decision-record Markdown files and headings otherwise; rust (one claim per crate and module doc) is never inferred. delta reads Delta Lake tables and requires the oml-lake build",
         "Adapter: adr, headings or lines. Defaults to adr for decision-record Markdown files and headings otherwise. " + NOT_RELEASED + " `rust` (one claim per crate and module doc, never inferred) and `delta` (Delta Lake tables, requiring the oml-lake build)"),
        ("With --adapter delta, canonical source URI", NOT_RELEASED + " With --adapter delta, canonical source URI"),
    ],
    "mcp": [
        ("`oml-md/1` \\| `oml-turn/1` \\| `oml-rustdoc/1` \\| `oml-crate/1`", "`oml-md/1` \\| `oml-turn/1`; `oml-rustdoc/1` and `oml-crate/1` are not released yet (next release)"),
    ],
}


def mark_unreleased(text: str, page: str) -> str:
    for old, new in UNRELEASED.get(page, []):
        if old not in text:
            sys.exit(f"docgen.UNRELEASED[{page!r}] names text the build no longer prints: {old[:60]!r}; remove the entry")
        text = text.replace(old, new)
    return text


def front_matter(answers: str) -> str:
    return f'---\nstatus: Generated\nverified: {VERIFIED}\nanswers: "{answers}"\n---\n'


def finish(path: pathlib.Path, text: str, check: bool) -> int:
    """Write `text` to `path`, or under --check say whether the file already holds it."""
    text = text.rstrip("\n") + "\n"
    shown = path.relative_to(ROOT)
    if check:
        current = path.read_text() if path.exists() else ""
        if current != text:
            print(f"{shown} differs from its source; run the generator and commit the result", file=sys.stderr)
            return 1
        print(f"{shown} matches its source")
        return 0
    path.write_text(text)
    print(f"wrote {shown}")
    return 0
