"""Shared helpers for the scripts that write docs/ pages from the code and the contracts.

A generated page is a function of its source: each generator renders the page text, then either
writes it or, under --check, compares it with the file on disk and exits 1 on any difference.
`VERIFIED` is the date a person last confirmed the generated pages against a release; raise it in
the same change that regenerates them for a new one.
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
VERIFIED = "2026-11-06"
BANNER = "Generated by `{script}`; edit the source, not this page."

# "(ADR-0039 d15)", "(proposed ADR-0037 d2, d10)", "(admin key role; ADR-0049 d4)", "ADR-0015", "#117".
_PAREN_ONLY = re.compile(r"\s*\((?:[^()]*?;\s*)?(?:proposed\s+)?(?:ADR-\d+(?:\s*d[\d, –-]+\d?)?(?:\s*,\s*)?)+\)")
_ADR = re.compile(r"[,;]?\s*(?:proposed\s+)?ADR-\d+(?:\s*d\d+(?:\s*[-–,]\s*d?\d+)*)?")
_ISSUE = re.compile(r"\s*\(?#\d{2,4}\)?")
_DNUM = re.compile(r"\b[Dd]\d{1,2}(?:[-–,]\s*d?\d{1,2})*\b")


def strip_handles(text: str) -> str:
    """Remove ADR and issue handles from a sentence; they belong to contributors, not readers."""
    before = None
    while before != text:
        before = text
        text = _PAREN_ONLY.sub("", text)
    text = re.sub(r"\(([^()]*?);\s*(?:proposed\s+)?ADR-\d+[^()]*\)", r"(\1)", text)
    text = _ADR.sub("", text)
    text = _ISSUE.sub("", text)
    text = re.sub(r"\s*\([Dd]\d{1,2}(?:\s*[-–,]\s*[Dd]?\d{1,2})*\)", "", text)
    text = re.sub(r"\(\s*[;,]\s*", "(", text)
    text = re.sub(r"\(\s*\)", "", text)
    text = re.sub(r"\s+([,.;:)])", r"\1", text)
    text = re.sub(r"\(\s+", "(", text)
    return re.sub(r"[ \t]{2,}", " ", text).strip()


def front_matter(answers: str) -> str:
    return f'---\nstatus: Generated\nverified: {VERIFIED}\nanswers: "{answers}"\n---\n'


def finish(path: pathlib.Path, text: str, check: bool) -> int:
    """Write `text` to `path`, or under --check say whether the file already holds it."""
    text = text.rstrip("\n") + "\n"
    shown = path.relative_to(ROOT)
    if check:
        current = path.read_text() if path.exists() else ""
        if current != text:
            print(f"{shown} differs from its source; run the generator and commit the result", file=sys.stderr)
            return 1
        print(f"{shown} matches its source")
        return 0
    path.write_text(text)
    print(f"wrote {shown}")
    return 0
