def tokens() -> dict:
    return json.loads((DESIGN / "tokens.json").read_text())


def ident(name: str) -> str:
    """A token name as a custom property name: a dot is escaped (`--space-0\\.5`)."""
    return "--" + name.replace(".", "\\.")


def theme_vars(t: dict, theme: str) -> list[tuple[str, str]]:
    out = []
    for group in ("color", "shadow"):
        for tok in t[group]["tokens"]:
            v = tok["value"]
            out.append((tok["name"], v[theme] if isinstance(v, dict) else v))
    return out


def static_vars(t: dict) -> list[tuple[str, str]]:
    out = []
    for group in ("spacing", "radius", "size", "typescale"):
        for tok in t[group]["tokens"]:
            out.append((tok["name"], str(tok["value"])))
    for name, stack in t["type"]["families"].items():
        out.append((f"font-{name}", stack))
    return out


def logo_colours() -> dict[str, dict[str, str]]:
    """The mark's three colours per theme, read from the wordmark files themselves, so the
    inline wordmark draws exactly what the files draw (ADR-0069 d6)."""
    out = {}
    for theme, f in (("dark", "oml-wordmark-dark.svg"), ("light", "oml-wordmark-light.svg")):
        svg = (DESIGN / "assets" / f).read_text()
        ring = re.search(r'A24 24[^"]*" fill="none" stroke="(#[0-9A-Fa-f]{6})"', svg).group(1)
        star = re.search(r'r="11" fill="(#[0-9A-Fa-f]{6})"', svg).group(1)
        ink = re.search(r'r="5\.6" fill="(#[0-9A-Fa-f]{6})"', svg).group(1)
        out[theme] = {"logo-ring": ring.lower(), "logo-star": star.lower(), "logo-ink": ink.lower()}
    return out


def decls(pairs) -> str:
    return ";".join(f"{ident(n)}:{v}" for n, v in pairs)


def tokens_css(t: dict, selectors: dict[str, str] | None = None, media: bool = True) -> str:
    """Night on :root, paper under prefers-color-scheme: light (or under the given selectors)."""
    logos = logo_colours()
    dark = theme_vars(t, "dark") + list(logos["dark"].items())
    light = theme_vars(t, "light") + list(logos["light"].items())
    lines = [f"/* {HEAD} */", f":root{{{decls(static_vars(t))}}}"]
    if selectors is None:
        lines.append(f":root{{color-scheme:dark;{decls(dark)}}}")
        if media:
            lines.append(f"@media (prefers-color-scheme:light){{:root{{color-scheme:light;{decls(light)}}}}}")
    else:
        lines.append(f"{selectors['dark']}{{color-scheme:dark;{decls(dark)}}}")
        lines.append(f"{selectors['light']}{{color-scheme:light;{decls(light)}}}")
    return "\n".join(lines) + "\n"


def glyph_svg(name: str) -> str:
    return (DESIGN / "glyphs" / f"{name}.svg").read_text().strip()


def inline_glyph(name: str) -> str:
    svg = glyph_svg(name)
    return svg.replace(' xmlns="http://www.w3.org/2000/svg"', "").replace(
        "<svg ", f'<svg class="glyph g-{name}" aria-hidden="true" focusable="false" ', 1)


def inline_mark(file: str, cls: str) -> str:
    """A mark file as inline SVG whose colours come from the stylesheet's --logo-* properties."""
    svg = (DESIGN / "assets" / file).read_text().strip()
    svg = re.sub(r"<title>.*?</title><desc>.*?</desc>", "", svg)
    svg = re.sub(r' role="img" aria-label="[^"]*"', ' aria-hidden="true" focusable="false"', svg)
    svg = re.sub(r' width="\d+" height="\d+"', "", svg, count=1)
    svg = svg.replace(' xmlns="http://www.w3.org/2000/svg"', "").replace("<svg ", f'<svg class="{cls}" ', 1)
    svg = re.sub(r'(A24 24[^"]*" fill="none") stroke="#[0-9A-Fa-f]{6}"', r'\1 class="lg-ring"', svg)
    svg = re.sub(r'r="11" fill="#[0-9A-Fa-f]{6}"', 'r="11" class="lg-star"', svg)
    svg = re.sub(r'fill="#[0-9A-Fa-f]{6}"', 'class="lg-ink"', svg)
    return svg


def brand_rs(t: dict) -> str:
    ground = next(tok["value"] for tok in t["color"]["tokens"] if tok["name"] == "ground")

    def raw(s: str) -> str:
        assert '"#' not in s
        return f'r#"{s}"#'
    out = [
        f"// {HEAD}",
        "//! The design system's marks and glyphs as inline SVG (ADR-0069 d3, d6): the pages run",
        "//! under `default-src 'none'`, so nothing is fetched and the stylesheet colours them.",
        "",
        "/// The `ground` token per theme, for `theme-color`.",
        f'pub const GROUND_DARK: &str = "{ground["dark"]}";',
        f'pub const GROUND_LIGHT: &str = "{ground["light"]}";',
        "",
        "/// The wordmark, for the page header from 600px.",
        f"pub const WORDMARK: &str = {raw(inline_mark('oml-wordmark-dark.svg', 'wm'))};",
        "",
        "/// The mark alone, for the page header below 600px.",
        f"pub const MARK: &str = {raw(inline_mark('oml-mark.svg', 'mk'))};",
        "",
        "/// Each glyph by name: the state glyphs, the markers and the actors.",
        "pub const GLYPHS: &[(&str, &str)] = &[",
    ]
    for name in WEB_GLYPHS:
        out.append(f'    ("{name}", {raw(inline_glyph(name))}),')
    out.append("];")
    return "\n".join(out) + "\n"


def mask_url(name: str) -> str:
    svg = glyph_svg(name).replace("currentColor", "#000").replace('"', "'")
    return 'url("data:image/svg+xml,' + urllib.parse.quote(svg, safe=" =:/'.,-") + '")'


