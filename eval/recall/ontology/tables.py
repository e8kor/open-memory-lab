#!/usr/bin/env python3
"""Print results/tables.md from this directory's results and the committed ../results.

    python3 eval/recall/ontology/tables.py > eval/recall/ontology/results/tables.md

Standard library only. Paired bootstrap: 2000 resamples over queries, seed 11, 95% interval.
"""

import json
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import metrics  # noqa: E402

MAIN = ["any", "any+syn", "any+term", "any+rareterm", "any+syn+term", "any+syn+boost",
        "bm25", "bm25+syn", "bm25+term", "bm25+rareterm", "bm25+syn+term", "bm25+syn+boost", "dense", "hybrid_rrf"]
TAGSETS = ["bm25+term", "bm25+term@lexical", "bm25+term@noisy",
           "bm25+syn+boost", "bm25+syn+boost@lexical", "bm25+syn+boost@noisy",
           "any+term", "any+term@lexical", "any+term@noisy"]
PAIRS = [("any", "any+syn"), ("any", "any+term"), ("any", "any+syn+term"),
         ("bm25", "bm25+syn"), ("bm25", "bm25+term"), ("bm25", "bm25+rareterm"), ("any", "any+rareterm"), ("bm25", "bm25+syn+term"),
         ("bm25", "bm25+syn+boost"), ("bm25", "bm25+term@lexical"), ("bm25", "bm25+term@noisy"),
         ("bm25+term", "hybrid_rrf"), ("bm25+term", "dense")]


def load(name):
    p = HERE / "results" / f"{name}.json"
    if not p.exists():
        p = HERE.parent / "results" / f"{name}.json"
    return json.loads(p.read_text())


def boot(diffs, n=2000, seed=11):
    rnd = random.Random(seed)
    means = sorted(sum(rnd.choice(diffs) for _ in diffs) / len(diffs) for _ in range(n))
    return means[int(0.025 * n)], means[int(0.975 * n)]


def main():
    _, queries = metrics.load()
    res = {m: load(m) for m in set(MAIN + TAGSETS + [b for p in PAIRS for b in p])}
    print("# Ontology arms of the recall eval\n")
    print("Generated by `tables.py`; `dense` and `hybrid_rrf` are the committed "
          "`../results/` runs.\n")
    print("## Overall, curated tags\n")
    print(metrics.overall_table({m: res[m]["summary"] for m in MAIN}).replace(" n/a |", " – |"))
    for metric, title in [("s5", "success@5"), ("s1", "success@1"), ("ndcg10", "nDCG@10")]:
        print(f"\n## {title} by category\n")
        print(metrics.markdown_table({m: res[m]["summary"] for m in MAIN}, metric))
    print("\n## Tag sets: curated, lexical (server-side label match, no judgement), noisy\n")
    print(metrics.overall_table({m: res[m]["summary"] for m in TAGSETS}).replace(" n/a |", " – |"))
    print("\n## Paired differences and the queries each arm made worse\n")
    print("| base → arm | Δ success@5 (95% CI) | Δ nDCG@10 (95% CI) | queries better / worse "
          "(nDCG@10) | success@5 gained / lost | paraphrase Δ success@5 |")
    print("|---|---|---|---|---|---|")
    for a, b in PAIRS:
        qa, qb = res[a]["per_query"], res[b]["per_query"]
        d5 = [qb[q["id"]]["scores"]["s5"] - qa[q["id"]]["scores"]["s5"] for q in queries]
        dn = [qb[q["id"]]["scores"]["ndcg10"] - qa[q["id"]]["scores"]["ndcg10"] for q in queries]
        lo5, hi5 = boot(d5)
        lon, hin = boot(dn)
        better = sum(1 for x in dn if x > 1e-9)
        worse = sum(1 for x in dn if x < -1e-9)
        gained = sum(1 for x in d5 if x > 0)
        lost = sum(1 for x in d5 if x < 0)
        par = res[b]["summary"]["paraphrase"]["s5"] - res[a]["summary"]["paraphrase"]["s5"]
        print(f"| {a} → {b} | {sum(d5)/len(d5):+.3f} ({lo5:+.3f}, {hi5:+.3f}) | "
              f"{sum(dn)/len(dn):+.3f} ({lon:+.3f}, {hin:+.3f}) | {better} / {worse} | "
              f"{gained} / {lost} | {par:+.2f} |")
    matched = res["bm25+term"]["per_query"]
    n_match = sum(1 for q in queries if matched[q["id"]]["matched_terms"])
    per_q = [len(matched[q["id"]]["matched_terms"]) for q in queries]
    print(f"\n{n_match} of {len(queries)} queries match at least one term label; "
          f"{sum(per_q) / len(per_q):.2f} terms per query on average, at most {max(per_q)}.")
    by_cat = {}
    for q in queries:
        by_cat.setdefault(q["category"], []).append(1 if matched[q["id"]]["matched_terms"] else 0)
    print("\n| category | queries matching a term |\n|---|---:|")
    for c in metrics.CATEGORIES:
        print(f"| {c} | {sum(by_cat[c])} / {len(by_cat[c])} |")


if __name__ == "__main__":
    main()
